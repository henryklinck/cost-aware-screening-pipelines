"""Phase-1 experiment driver (spec sections 7, 8, 32).

End to end:

    synthetic library  ->  5 simulated models  ->  exhaustive pipeline x threshold search
    ->  constrain to testing budget  ->  cost/recall table + Pareto frontier
    ->  Figures 1-5  ->  reproducibility manifest

Run from the repo root:

    python experiments/simulation/run_simulation.py --config configs/simulation.yaml

Everything written under results/ is generated by the simulation; nothing is invented.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict

import pandas as pd
import yaml

# Allow running as a plain script (no install needed) as well as via -m.
REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "src"))

from screening.metrics import model_quality_metrics  # noqa: E402
from screening.models import (  # noqa: E402
    ModelSpec,
    build_simulated_models,
    default_model_specs,
)
from screening.optimization import (  # noqa: E402
    constrain_to_test_budget,
    pareto_frontier,
    recall_at_budgets,
    search_all,
)
from screening.simulation import make_library  # noqa: E402
from screening.utils import ExperimentRecord, Timer  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
import plots  # noqa: E402


def load_config(path: Path) -> dict:
    with open(path) as fh:
        return yaml.safe_load(fh)


def build_models_from_config(cfg: dict, library, correlation: float, seed: int):
    specs_cfg = cfg.get("models")
    if specs_cfg:
        specs = [ModelSpec(**s) for s in specs_cfg]
    else:
        specs = default_model_specs()
    return build_simulated_models(library, specs, correlation=correlation, seed=seed)


def most_expensive_single_model_cost(models, n_molecules: int) -> float:
    """Cost of running the single most expensive model over the whole library.

    This is the reference "most expensive single-model strategy" of spec section 20.
    """
    return max(m.estimate_cost(n_molecules) for m in models.values())


def run_condition(cfg: dict, n_molecules: int, prevalence: float, correlation: float,
                  seed: int) -> pd.DataFrame:
    """Build a world under given knobs and return the constrained-to-budget search df."""
    lib = make_library(
        n_molecules=n_molecules,
        mu=cfg["library"]["mu"],
        sigma=cfg["library"]["sigma"],
        sigma_assay=cfg["library"]["sigma_assay"],
        prevalence=prevalence,
        hits_on="true" if cfg["library"]["hits_on"] else "obs",
        seed=seed,
    )
    models = build_models_from_config(cfg, lib, correlation, seed + 1)
    df = search_all(
        lib, models,
        min_stages=cfg["search"]["min_stages"],
        max_stages=cfg["search"]["max_stages"],
        retention_values=tuple(cfg["search"]["retention_grid"]),
    )
    K = max(1, int(cfg["analysis"]["test_budget_fraction"] * lib.n))
    return constrain_to_test_budget(df, K)


def main() -> None:
    ap = argparse.ArgumentParser(description="Phase-1 synthetic screening simulation")
    ap.add_argument("--config", default=str(REPO_ROOT / "configs" / "simulation.yaml"))
    ap.add_argument("--outdir", default=str(REPO_ROOT / "results"))
    ap.add_argument("--skip-sweeps", action="store_true",
                    help="skip Figures 4/5 sweeps (faster)")
    args = ap.parse_args()

    cfg = load_config(Path(args.config))
    outdir = Path(args.outdir)
    seed = int(cfg["seed"])

    with Timer() as timer:
        # ---- Primary world ------------------------------------------------------
        lib = make_library(
            n_molecules=cfg["library"]["n_molecules"],
            mu=cfg["library"]["mu"],
            sigma=cfg["library"]["sigma"],
            sigma_assay=cfg["library"]["sigma_assay"],
            prevalence=cfg["library"]["prevalence"],
            hits_on="true" if cfg["library"]["hits_on"] else "obs",
            seed=seed,
        )
        correlation = float(cfg["model_error_correlation"])
        models = build_models_from_config(cfg, lib, correlation, seed + 1)

        print(f"Library: {lib.n:,} molecules | {lib.n_hits:,} hits "
              f"(prevalence {lib.prevalence:.3%}) | hit threshold {lib.hit_threshold:.3f}")

        # ---- Per-model quality (spec section 23) --------------------------------
        quality_rows = []
        for name, m in models.items():
            q = model_quality_metrics(m.scores, lib)
            q["model"] = name
            q["cost_per_molecule"] = m.spec.cost_per_molecule
            q["noise_std"] = m.spec.noise_std
            quality_rows.append(q)
        quality = pd.DataFrame(quality_rows).set_index("model")
        (outdir / "model_benchmarks").mkdir(parents=True, exist_ok=True)
        quality.to_csv(outdir / "model_benchmarks" / "model_quality.csv")
        print("\nPer-model quality:")
        print(quality[["noise_std", "cost_per_molecule", "spearman", "auroc",
                       "recall_top_0.01"]].round(3).to_string())

        # ---- Exhaustive search --------------------------------------------------
        df = search_all(
            lib, models,
            min_stages=cfg["search"]["min_stages"],
            max_stages=cfg["search"]["max_stages"],
            retention_values=tuple(cfg["search"]["retention_grid"]),
        )
        (outdir / "simulation").mkdir(parents=True, exist_ok=True)
        df.to_csv(outdir / "simulation" / "all_configurations.csv", index=False)

        # ---- Constrain to experimental testing budget --------------------------
        K = max(1, int(cfg["analysis"]["test_budget_fraction"] * lib.n))
        constrained = constrain_to_test_budget(df, K)
        frontier = pareto_frontier(constrained)
        (outdir / "pipelines").mkdir(parents=True, exist_ok=True)
        frontier.to_csv(outdir / "pipelines" / "pareto_frontier.csv", index=False)

        # Primary results table (spec section 8).
        table_cols = ["pipeline", "thresholds", "total_cost", "recall", "precision",
                      "enrichment", "hits_recovered", "final_molecules", "cost_per_hit"]
        frontier[table_cols].to_csv(
            outdir / "pipelines" / "primary_table.csv", index=False)

        # ---- Recall at fixed compute budgets (spec section 20) ------------------
        ref_cost = most_expensive_single_model_cost(models, lib.n)
        budgets = [f * ref_cost for f in cfg["analysis"]["compute_budget_fractions"]]
        rab = recall_at_budgets(constrained, budgets)
        rab["budget_fraction_of_max_single"] = cfg["analysis"]["compute_budget_fractions"]
        rab.to_csv(outdir / "pipelines" / "recall_at_budget.csv", index=False)

        # Best single-model strategy at any cost, and its constrained-frontier match.
        singles = constrained[constrained["n_stages"] == 1]
        best_single = singles.sort_values("recall", ascending=False).iloc[0]
        equal_recall_pipeline = frontier[frontier["recall"] >= best_single["recall"]]
        equal_recall_pipeline = (
            equal_recall_pipeline.sort_values("total_cost").iloc[0]
            if not equal_recall_pipeline.empty else None
        )

        print("\nPrimary trade-off (recall at compute budgets, "
              "budget as fraction of most-expensive single model on whole library):")
        print(rab[["budget_fraction_of_max_single", "total_cost", "recall",
                   "pipeline"]].round(3).to_string(index=False))

        print(f"\nBest single-model strategy (constrained): {best_single['pipeline']} "
              f"-> recall {best_single['recall']:.3f} at cost {best_single['total_cost']:,.0f}")
        if equal_recall_pipeline is not None:
            speedup = best_single["total_cost"] / equal_recall_pipeline["total_cost"]
            print(f"Cheapest pipeline matching that recall: "
                  f"{equal_recall_pipeline['pipeline']} -> recall "
                  f"{equal_recall_pipeline['recall']:.3f} at cost "
                  f"{equal_recall_pipeline['total_cost']:,.0f} ({speedup:.1f}x cheaper)")

        # ---- Figures ------------------------------------------------------------
        figdir = outdir / "figures"
        # Best single-model point per model (max recall each), for Figure 1 overlay.
        single_points = (
            singles.sort_values("recall", ascending=False)
            .groupby("stages", as_index=False).first()
        )
        plots.fig1_recall_vs_cost(constrained, frontier, figdir / "fig1_recall_vs_cost.png",
                                  single_model=single_points)
        plots.fig2_cost_per_hit(frontier, figdir / "fig2_cost_per_hit.png")

        # Figure 3: ordering, on a fixed 3-model set {A,C,E}.
        set_label = "A,C,E"
        target = {"A", "C", "E"}
        sub = constrained.copy()
        sub["model_set"] = sub["stages"].apply(lambda s: frozenset(s.split("->")))
        sub["first_model"] = sub["stages"].apply(lambda s: s.split("->")[0])
        sub = sub[sub["model_set"] == frozenset(target)]
        if not sub.empty:
            plots.fig3_ordering(sub, figdir / "fig3_ordering.png", set_label)

        # ---- Sweeps for Figures 4 & 5 ------------------------------------------
        if not args.skip_sweeps:
            sw = cfg["sweeps"]
            prev_frontiers: Dict[float, pd.DataFrame] = {}
            for prev in sw["prevalence_values"]:
                c = run_condition(cfg, sw["n_molecules"], prev, correlation, seed)
                prev_frontiers[prev] = pareto_frontier(c)
            plots.fig4_prevalence(prev_frontiers, figdir / "fig4_prevalence.png")

            corr_frontiers: Dict[float, pd.DataFrame] = {}
            for rho in sw["correlation_values"]:
                c = run_condition(cfg, sw["n_molecules"],
                                  cfg["library"]["prevalence"], rho, seed)
                corr_frontiers[rho] = pareto_frontier(c)
            plots.fig5_correlation(corr_frontiers, figdir / "fig5_correlation.png")

    # ---- Reproducibility manifest (spec section 29) ----------------------------
    record = ExperimentRecord(
        experiment_id=cfg["experiment_id"],
        config=cfg,
        seed=seed,
        runtime_seconds=timer.seconds,
        results={
            "n_molecules": lib.n,
            "n_hits": lib.n_hits,
            "prevalence": lib.prevalence,
            "hit_threshold": lib.hit_threshold,
            "n_configurations": int(len(df)),
            "n_constrained": int(len(constrained)),
            "n_pareto": int(len(frontier)),
            "reference_cost_max_single_model": ref_cost,
            "best_single_model": {
                "pipeline": best_single["pipeline"],
                "recall": float(best_single["recall"]),
                "cost": float(best_single["total_cost"]),
            },
            "cheapest_pipeline_matching_best_single": (
                None if equal_recall_pipeline is None else {
                    "pipeline": equal_recall_pipeline["pipeline"],
                    "recall": float(equal_recall_pipeline["recall"]),
                    "cost": float(equal_recall_pipeline["total_cost"]),
                }
            ),
        },
    )
    manifest_path = outdir / "simulation" / f"{cfg['experiment_id']}_manifest.json"
    record.to_json(manifest_path)
    print(f"\nRuntime: {timer.seconds:.1f}s")
    print(f"Manifest: {manifest_path}")
    print(f"Figures:  {outdir / 'figures'}")


if __name__ == "__main__":
    main()
